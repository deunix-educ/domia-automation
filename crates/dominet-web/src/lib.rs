//! DomiNet interface: server-side rendering (SSR) then hydration in WASM.
//!
//! - `app`: HTML shell, i18n provider, router and pages;
//! - `layout`: sidebar, dynamic navigation and content;
//! - `crud`: generic component of the administration pages;
//! - `server_fns`: server functions (called from the browser, run on the server side);
//! - `ssr` (feature `ssr`): assembly of the interface's HTTP service.

// Leptos idioms: components and their properties are passed by value, and view functions return
// `impl IntoView`s that nobody "must use" in the sense of `must_use`.
// The code generated by `#[server]` is `async` without `await` on the browser side (a simple call stub).
#![allow(
    clippy::must_use_candidate,
    clippy::needless_pass_by_value,
    clippy::unused_async,
    clippy::unused_async_trait_impl
)]

/// Translation key resolved later (`I18n::tr`). Does nothing but make the key detectable: the test
/// `tests/i18n.rs` counts it as used and checks that it exists in both languages.
macro_rules! tk {
    ($key:literal) => {
        $key
    };
}

